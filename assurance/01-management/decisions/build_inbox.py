#!/usr/bin/env python3
"""Build the decision inbox page from register.yaml.

The page is published as a claude.ai artifact with the `db` and `user` capabilities. The lead's
answers and requests for more explanation are saved in its store, in the collections `answers` and
`explain`, keyed by question id; Claude copies them back into register.yaml (README.md).

    python3 build_inbox.py --out PATH
"""


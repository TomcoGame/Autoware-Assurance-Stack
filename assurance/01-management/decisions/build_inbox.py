REPO_URL = "https://github.com/tomcogame/autoware-assurance-stack"


def md_inline(s: str) -> str:
    """Escape, collapse whitespace, then **bold** → <b> and `code` → <code>."""
    out = html.escape(" ".join(str(s).split()), quote=False)
    out = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", out)
    return re.sub(r"`([^`]+)`", r"<code>\1</code>", out)


def iso(v) -> str | None:
    d = check_decisions.as_date(v)
    return d.isoformat() if d else None


def ref_url(ref) -> str | None:
    ref = str(ref or "")
    if ref.startswith("https://"):
        return ref
    if re.fullmatch(r"[0-9a-f]{7,40}", ref):
        return f"{REPO_URL}/commit/{ref}"
    m = re.fullmatch(r"#?(\d+)", ref)
    return f"{REPO_URL}/pull/{m.group(1)}" if m else None


def card(d: dict, base: Path) -> dict:
    ans, ap, ex = d.get("answer") or {}, d.get("applied") or {}, d.get("explanation") or {}
    esc = lambda s: html.escape(str(s), quote=False)  # noqa: E731
    return {
        "id": d["id"],
        "q": md_inline(d["question"]),
        "why": md_inline(d["context"]),
        "rev": d["reversibility"],
        "claude": d.get("decider") == "claude",
        "blocks": esc(d["blocks"]),
        "gate": d.get("gate") or "",
        "asked": iso(d.get("asked")),
        "proceedAfter": iso(d.get("proceed_after")),
        "batch": d.get("batch"),
        "after": d.get("after") or [],
        "svg": (base / d["figure"]).read_text(encoding="utf-8").strip() if d.get("figure") else "",
        "cap": md_inline(d.get("caption", "")),
        "opts": [
            {
                "k": o["key"],
                "t": md_inline(o["title"]),
                "d": md_inline(o["detail"]),
                "rec": bool(o.get("recommended")),
            }
            for o in d["options"]
        ],
        "src": [esc(s) for s in d.get("sources", [])],
        "status": d["status"],
        "answer": (
            {
                "choice": ans.get("choice"),
                "via": ans.get("via"),
                "at": iso(ans.get("at")),
                "note": esc(ans.get("note", "")),
            }
            if ans
            else None
        ),
        "applied": (
            {
                "ref": esc(ap.get("ref")),
                "url": ref_url(ap.get("ref")),
                "record": esc(ap.get("record")),
                "at": iso(ap.get("at")),
            }
            if ap
            else None
        ),
        "explanation": (
            {"text": md_inline(ex.get("text", "")), "at": iso(ex.get("at"))} if ex else None
        ),
        "note": esc(d.get("note", "")),
    }


def build(entries: list[dict], base: Path = HERE, built: str | None = None) -> str:
    data = json.dumps([card(d, base) for d in entries], ensure_ascii=False, indent=1).replace(
        "</", "<\\/"
    )
    return TEMPLATE.replace("/*__REGISTER__*/[]", data).replace(
        "__BUILT__", built or dt.date.today().isoformat()
    )


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--register", type=Path, default=check_decisions.REGISTER)
    args = ap.parse_args(argv)
    entries = check_decisions.load(args.register)
    errs = check_decisions.check(entries, args.register.parent)
    if errs:
        print("\n".join(errs))
        return 1
    args.out.write_text(build(entries, args.register.parent), encoding="utf-8")
    print(f"wrote {args.out} ({len(entries)} questions)")
    return 0



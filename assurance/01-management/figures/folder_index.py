#!/usr/bin/env python3
"""Write the index page (README.md) and status figure (index-status.svg) of each numbered folder.

A page is built only from records that already exist, so it never needs editing by hand:

- the folder's row of the Layout table in assurance/README.md (what it holds, its clauses);
- its section of the WP-M-00 §3 register: the figure (one row per work product, a chip at each gate
  it is needed for, coloured by status) and a table linking each work product;
- its subfolders, with the title of their README when they have one.

Files are not listed (GitHub shows them above the page), so adding a file never makes a page stale.

    python3 folder_index.py            # write every page and figure
    python3 folder_index.py --check    # fail if one is stale, or a register row has no file
"""

from __future__ import annotations

from pathlib import Path
import re
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import figkit as fk  # noqa: E402
import wpregister  # noqa: E402

README = fk.ASSURANCE / "README.md"
SVG_NAME = "index-status.svg"
GENERATED = (
    "<!-- Generated by assurance/01-management/figures/folder_index.py; do not edit by hand. -->"
)
W = 640
X0, XG, ROW = 24, 360, 40


def folders() -> list[str]:
    return sorted(
        p.name for p in fk.ASSURANCE.iterdir() if p.is_dir() and re.match(r"\d\d-", p.name)
    )


def layout() -> dict[str, tuple[str, str]]:
    """{folder: (content, clauses)} from the Layout table of assurance/README.md."""
    head, rows = fk.table(fk.section(README.read_text(encoding="utf-8"), "## Layout"), "Folder")
    return {
        fk.plain(r[fk.col(head, "Folder")]).strip("/"): (
            r[fk.col(head, "Content")],
            fk.plain(r[fk.col(head, "Primary standard clauses")]),
        )
        for r in rows
    }


def rel(target: Path, folder: str) -> str:
    """A path in the assurance tree as a link from the folder's README."""
    base = (fk.ASSURANCE / folder).resolve()
    target = target.resolve()
    try:
        return target.relative_to(base).as_posix()
    except ValueError:
        return Path("..", target.relative_to(fk.ASSURANCE)).as_posix()


def rebase(cell: str, folder: str) -> str:
    """Relative links of a cell from assurance/README.md, rewritten to work from the folder."""

    def fix(m: re.Match) -> str:
        url = m.group(2)
        if re.match(r"[a-z]+:|#|/", url):
            return m.group(0)
        path, _, frag = url.partition("#")
        return f"[{m.group(1)}]({rel(fk.ASSURANCE / path, folder)}{'#' + frag if frag else ''})"

    return re.sub(r"\[([^\]]*)\]\(([^)]+)\)", fix, cell)


def title_of(md: Path) -> str:
    for ln in md.read_text(encoding="utf-8", errors="replace").splitlines():
        if ln.startswith("# "):
            return fk.plain(ln[2:])
    return ""


def figure(folder: str, title: str, items: list[wpregister.Product], gates: list[str]) -> str:
    gw = (W - X0 - XG) / len(gates)
    sub = f"WP-M-00 §3 ({title}): a chip at each gate the work product is needed for"
    lines = fk.wrap(sub, W - 2 * X0, "t")
    body = [fk.text(X0, 32, f"{folder}: work products by gate", "h")]
    body += [fk.text(X0, 54 + 17 * i, ln, "t") for i, ln in enumerate(lines)]
    y = 54 + 17 * (len(lines) - 1) + 14
    body.append(fk.el("line", None, x1=X0, y1=fk.num(y), x2=W - X0, y2=fk.num(y), class_="hair"))
    y += 24
    for i, g in enumerate(gates):
        body.append(fk.text(XG + gw * i + gw / 2, y, g, "tb", "middle"))
    y += 8
    for k, p in enumerate(items):
        if k % 2 == 0:
            body.append(
                fk.el(
                    "rect",
                    None,
                    x=X0 - 8,
                    y=fk.num(y),
                    width=W - 2 * (X0 - 8),
                    height=ROW,
                    rx=4,
                    class_="card",
                )
            )
        body.append(fk.text(X0, y + 17, p.wid, "tb"))
        body.append(fk.text(X0, y + 32, fk.fit(p.name, XG - X0 - 12, "s"), "s"))
        for g in p.gates:
            body.append(
                fk.el(
                    "rect",
                    None,
                    x=fk.num(XG + gw * g + 5),
                    y=fk.num(y + 13),
                    width=fk.num(gw - 10),
                    height=14,
                    rx=7,
                    class_=fk.STATUS_CLASS[p.status],
                )
            )
        y += ROW
    y += 24
    x = X0
    for s in sorted({p.status for p in items}, key=list(fk.STATUS_CLASS).index):
        n = sum(1 for p in items if p.status == s)
        label = f"{fk.STATUS_NAME[s]} ({n})"
        body += [
            fk.el(
                "rect",
                None,
                x=x,
                y=fk.num(y - 11),
                width=26,
                height=14,
                rx=7,
                class_=fk.STATUS_CLASS[s],
            ),
            fk.text(x + 32, y, label, "t"),
        ]
        x += 32 + fk.width(label, "t") + 20
    y += 18
    desc = (
        f"Work products of {folder} from WP-M-00 §3, with the gates they are needed for and their status: "
        + "; ".join(f"{p.wid} {p.name}: {p.gate_text}, {fk.STATUS_NAME[p.status]}" for p in items)
        + "."
    )
    return fk.svg(W, int(y), f"{folder}: work products by gate and status", desc, body)


def page(folder: str, lay: dict, reg: wpregister.Register) -> tuple[str, str | None]:
    if folder not in lay:
        raise fk.FigureError(f"assurance/README.md Layout table has no row for {folder}/")
    content, clauses = lay[folder]
    sec = next((s for s in reg.sections if s[2] == folder), None)
    items = [p for p in reg.products if p.folder == folder]
    gates = [g for g, _ in reg.gates]
    out = [GENERATED, "", f"# {folder}", "", rebase(content, folder) + ".", ""]
    if clauses and clauses != "n/a":
        out += [f"Standard clauses: {clauses}.", ""]
    svg = None
    if items:
        svg = figure(folder, sec[1], items, gates)
        counts = ", ".join(
            f"{sum(1 for p in items if p.status == s)} {fk.STATUS_NAME[s].lower()}"
            for s in sorted({p.status for p in items}, key=list(fk.STATUS_CLASS).index)
        )
        per_gate = ", ".join(
            f"{sum(gi in p.gates for p in items)} at {g}"
            for gi, g in enumerate(gates)
            if any(gi in p.gates for p in items)
        )
        reg_link = rel(wpregister.WP_M_00, folder)
        out += [
            f"![The {len(items)} work products of this folder, one row each, with a chip at each gate it is needed for, "
            f"coloured by its status in the WP-M-00 register: {per_gate}; {counts}]({SVG_NAME})",
            "",
            f"*Drawn from [WP-M-00]({reg_link}#3-register) §{sec[0]}, which also has the clauses of each work product.*",
            "",
            "## Work products",
            "",
            "| ID | Work product | Gate | Status |",
            "|---|---|---|---|",
        ]
        for p in items:
            if not p.path.is_file():
                raise fk.FigureError(f"WP-M-00 {p.wid} links {p.href}, which does not exist")
            out.append(
                f"| [{p.wid}]({rel(p.path, folder)}) | {p.name} | {p.gate_text} | {fk.STATUS_NAME[p.status]} |"
            )
        out.append("")
    subs = sorted(
        d for d in (fk.ASSURANCE / folder).iterdir() if d.is_dir() and not d.name.startswith(".")
    )
    if subs:
        out += ["## Subfolders", "", "| Folder | What it holds |", "|---|---|"]
        for d in subs:
            readme = d / "README.md"
            what = title_of(readme) if readme.is_file() else "—"
            link = f"{d.name}/README.md" if readme.is_file() else f"{d.name}/"
            out.append(f"| [`{d.name}/`]({link}) | {what} |")
        out.append("")
    if not items:
        out += ["This folder has no work products in the register.", ""]
    return "\n".join(out), svg


def build() -> dict[Path, str]:
    lay, reg = layout(), wpregister.load()
    outputs: dict[Path, str] = {}
    for folder in folders():
        md, svg = page(folder, lay, reg)
        outputs[fk.ASSURANCE / folder / "README.md"] = md
        if svg:
            outputs[fk.ASSURANCE / folder / SVG_NAME] = svg
    listed = {p.folder for p in reg.products}
    missing = sorted(f for f in listed if f not in folders() and re.match(r"\d\d-", f))
    if missing:
        raise fk.FigureError(
            f"register sections name folders that do not exist: {', '.join(missing)}"
        )
    return outputs


if __name__ == "__main__":
    fk.run(build, __doc__)
